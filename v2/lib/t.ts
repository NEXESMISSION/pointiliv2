/** Letters that are written several ways become one: أ إ آ → ا, ة → ه, ى → ي, no accents. */
export function plain(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f\u064b-\u065f\u0670]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .trim();
}

/** Does this kind answer what the owner typed? Every word has to be found. */
export function kindMatches(kind: string, query: string): boolean {
  const hay = plain(`${t.kinds[kind] ?? ""} ${KIND_WORDS[kind] ?? ""} ${kind}`);
  return plain(query)
    .split(" ")
    .filter(Boolean)
    .every((w) => hay.includes(w));
}

/** Counting the Tunisian way: حريف واحد, زوز حرفاء, 5 حرفاء, 12 حريف. */
export function counted(n: number, one: string, two: string, few: string, many: string): string {
  if (n === 1) return one;
  if (n === 2) return two;
  const r = n % 100;
  return r >= 3 && r <= 10 ? `${n} ${few}` : `${n} ${many}`;
}
